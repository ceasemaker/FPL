"""Turn the production result files into LaTeX macros and tables for the report.

    python analysis/points_forecast_report/make_tables.py

Inputs (all next to this file, each produced by a production run):
    headline.json       the stored backtest evaluation (walk-forward, reference model)
    robustness.json     robustness.py
    sensitivity.json    sensitivity.py
    usage_eval.json     usage_eval.py
    usage_coverage.json usage_coverage.py
    possession.json     possession_lost_check.py

Outputs: results.tex (one macro per number used in the text) and the tables
*_table.tex. The report never types a result by hand.
"""
from __future__ import annotations

import json
from pathlib import Path

HERE = Path(__file__).resolve().parent
SEASONS = {"2023": "A", "2024": "B", "2025": "C"}  # macro suffixes: 2023/24, 2024/25, 2025/26


def load(name: str) -> dict:
    return json.loads((HERE / name).read_text())


def num(value: float, digits: int = 2) -> str:
    return f"{value:.{digits}f}"


def signed(value: float, digits: int = 2) -> str:
    text = f"{abs(value):.{digits}f}"
    if float(text) == 0:
        return f"${text}$"
    return f"${'+' if value > 0 else '-'}{text}$"


def interval(entry: dict, digits: int = 2) -> str:
    return f"{signed(entry['mean'], digits)} ({signed(entry['low'], digits)} to {signed(entry['high'], digits)})"


class Macros:
    def __init__(self) -> None:
        self.lines: list[str] = []

    def add(self, name: str, value: str) -> None:
        assert name.isalpha(), name
        self.lines.append(f"\\newcommand{{\\{name}}}{{{value}}}")

    def write(self) -> None:
        (HERE / "results.tex").write_text("% Generated by make_tables.py; do not edit.\n" + "\n".join(self.lines) + "\n")


def table(path: str, header: str, rows: list[str], spec: str) -> None:
    lines = [f"\\begin{{tabular}}{{{spec}}}", r"\toprule", header + r" \\", r"\midrule", *rows, r"\bottomrule", r"\end{tabular}"]
    (HERE / path).write_text("\n".join(lines) + "\n")


def main() -> None:
    m = Macros()
    head, rob, sens, usage, poss, cover = (load(n) for n in
                                     ("headline.json", "robustness.json", "sensitivity.json", "usage_eval.json",
                                      "possession.json", "usage_coverage.json"))

    # ------------------------------------------------------- headline
    acc = head["accuracy"]
    m.add("nTestRows", f"{acc['player_weeks']:,}".replace(",", "{,}"))
    m.add("maeModel", num(acc["model_mae"], 3)); m.add("maeForm", num(acc["form_mae"], 3))
    m.add("corrModel", num(acc["model_corr"], 3)); m.add("corrForm", num(acc["form_corr"], 3))
    cap = head["captain"]
    for key, name in (("model", "Model"), ("elite", "Elite"), ("premium", "Premium"), ("form", "Form"), ("best", "Best")):
        m.add(f"cap{name}", num(cap["points_per_week"][key]))
    m.add("capRegret", num(cap["regret"]))
    for key, name in (("elite", "Elite"), ("premium", "Premium"), ("form", "Form")):
        v = cap["versus"][key]
        m.add(f"vs{name}", interval(v)); m.add(f"vs{name}Mean", signed(v["mean"]))
        m.add(f"vs{name}Low", signed(v["low"])); m.add(f"vs{name}High", signed(v["high"]))
        m.add(f"vs{name}Plot", f"{v['low']:.3f},{v['mean']:.3f},{v['high']:.3f}")
    for season, suffix in SEASONS.items():
        row = cap["by_season"][season]
        for key, name in (("model", "Model"), ("elite", "Elite"), ("premium", "Premium"), ("form", "Form")):
            m.add(f"cap{name}{suffix}", num(row[key]))
    line = head["lineup"]
    m.add("nSquadWeeks", f"{line['squad_weeks']:,}".replace(",", "{,}"))
    for key, name in (("model", "Model"), ("manager", "Manager"), ("form", "Form")):
        m.add(f"line{name}", num(line["points_per_week"][key]))
    for key, name in (("manager", "Manager"), ("form", "Form")):
        v = line["versus"][key]
        m.add(f"lineVs{name}", interval(v)); m.add(f"lineVs{name}Plot", f"{v['low']:.3f},{v['mean']:.3f},{v['high']:.3f}")

    # ----------------------------------------------------- robustness
    it = rob["iterations"]
    m.add("iterMin", str(it["min"])); m.add("iterMedian", f"{it['median']:.0f}"); m.add("iterMax", str(it["max"]))
    ra = rob["accuracy"]
    m.add("rhoModel", num(ra["weekly_spearman_all"]["pred"])); m.add("rhoForm", num(ra["weekly_spearman_all"]["form_scaled"]))
    m.add("rhoReg", num(ra["weekly_spearman_all"]["reg"]))
    m.add("rhoCandModel", num(ra["weekly_spearman_candidates"]["pred"]))
    m.add("rhoCandForm", num(ra["weekly_spearman_candidates"]["form_scaled"]))
    m.add("rhoCandReg", num(ra["weekly_spearman_candidates"]["reg"]))
    m.add("maeGainFormScaled", interval(ra["paired_weekly_mae_gain"]["vs_form_scaled"], 3))
    m.add("maeGainReg", interval(ra["paired_weekly_mae_gain"]["vs_regression"], 3))
    m.add("calSlope", num(ra["calibration"]["slope"])); m.add("calIntercept", num(ra["calibration"]["intercept"]))
    m.add("nCandRows", f"{ra['candidates_mins60']['n']:,}".replace(",", "{,}"))
    rc = rob["captain"]
    for key, name in (("form_scaled", "FormScaled"), ("regression", "Reg")):
        m.add(f"cap{name}", num(rc["points_per_week"][key]))
        m.add(f"vs{name}", interval(rc[f"vs_{key}"]["iid"]))
    m.add("nRegularWeeks", str(rob["weeks"]["regular"])); m.add("nIrregularWeeks", str(rob["weeks"]["irregular"]))
    autocorrs = [rc[f"vs_{k}"]["lag1_autocorr"] for k in ("elite", "premium", "form", "form_scaled", "regression")]
    m.add("acMin", signed(min(autocorrs))); m.add("acMax", signed(max(autocorrs)))
    uc = cover
    m.add("usageCover", f"{100 * uc['with_usage']:.0f}\\%")
    m.add("usageMissNoPL", f"{100 * uc['missing_no_pl_minutes_last_season']:.0f}\\%")
    m.add("usageMissOther", f"{100 * uc['missing_despite_pl_minutes_last_season']:.0f}\\%")
    m.add("usageCoverRegulars", f"{100 * uc['regulars_with_usage']:.0f}\\%")

    # Captain comparisons: every comparator, iid / block / per season / regular weeks.
    names = {"elite": "Top-100 consensus$^b$", "premium": "Premium attacker", "form": "Recent form",
             "form_scaled": "Recent form $\\times$ fixtures", "regression": "Ridge regression"}
    rows = []
    for key, label in names.items():
        r = rc[f"vs_{key}"]
        blocks = {b["block"]: b for b in r["blocks"]}
        seasons = " & ".join(signed(r["by_season"][s]["mean"]) for s in ("2023", "2024", "2025"))
        rows.append(f"{label} & {num(rc['points_per_week'][key])} & {interval(r['iid'])} & "
                    f"{signed(blocks[6]['low'])} to {signed(blocks[6]['high'])} & {seasons} & {signed(r['regular_weeks']['mean'])} \\\\")
    table("captain_table.tex",
          r"Comparator & Pts/wk & Model minus comparator (95\% CI) & Block CI$^a$ & 23/24 & 24/25 & 25/26 & Regular wks",
          rows, "lccccccc")

    # Accuracy table.
    rows = []
    for key, label in (("pred", "Model"), ("form", "Recent form"), ("form_scaled", "Recent form $\\times$ fixtures"), ("reg", "Ridge regression")):
        a, c = ra["all"][key], ra["candidates_mins60"][key]
        rows.append(f"{label} & {num(a['mae'], 3)} & {num(a['rmse'], 3)} & {num(a['corr'], 3)} & "
                    f"{num(ra['weekly_spearman_all'][key])} & {num(c['mae'], 3)} & {num(ra['weekly_spearman_candidates'][key])} \\\\")
    table("accuracy_table.tex",
          r" & MAE & RMSE & Pearson & Weekly rank & MAE, regulars & Weekly rank, regulars", rows, "lcccccc")

    # Lineup decomposition.
    rl = rob["lineup"]
    rows = []
    for key, label in (("model", "Model"), ("manager", "Managers' own choices"), ("form", "Recent form"),
                       ("form_scaled", "Recent form $\\times$ fixtures"), ("regression", "Ridge regression")):
        pw = rl["per_week"][key]
        diff = "" if key == "model" else (f"{interval(rl[f'vs_{key}']['eleven'])} & {interval(rl[f'vs_{key}']['armband'])}")
        rows.append(f"{label} & {num(pw['eleven'])} & {num(pw['armband'])} & {diff if diff else '& '} \\\\")
    table("lineup_table.tex",
          r" & Eleven & Armband & Model minus: eleven (95\% CI) & armband (95\% CI)", rows, "lccll")

    # ---------------------------------------------------- sensitivity
    base = sens["baseline"]
    rows = []
    for name, row in sens.items():
        label = "Reference model" if name == "baseline" else name[0].upper() + name[1:]
        rows.append(f"{label} & {num(row['mae'], 3)} & {num(row['corr'], 3)} & {num(row['captain'])} & "
                    f"{signed(row['versus']['elite']['mean'])} & {signed(row['versus']['premium']['mean'])} & "
                    f"{signed(row['versus']['form']['low'])} \\\\")
        if name in ("baseline", "without minutes and starts"):
            rows.append(r"\midrule")
    table("sensitivity_table.tex", r" & MAE & Corr. & Captain & vs top-100 & vs premium & vs form, lower CI", rows, "lcccccc")
    variants = {k: v for k, v in sens.items() if k != "baseline"}
    m.add("nVariants", str(len(variants)))
    m.add("sensMaeSpread", num(max(abs(v["mae"] - base["mae"]) for v in variants.values()), 3))
    m.add("sensCorrSpread", num(max(abs(v["corr"] - base["corr"]) for v in variants.values()), 3))
    caps = [v["captain"] for v in sens.values()]
    m.add("sensCapMin", num(min(caps))); m.add("sensCapMax", num(max(caps)))
    m.add("sensPremLowMin", signed(min(v["versus"]["premium"]["low"] for v in sens.values())))
    m.add("sensEliteHighMax", signed(max(v["versus"]["elite"]["high"] for v in sens.values())))
    m.add("sensFormFail", str(sum(1 for v in sens.values() if v["versus"]["form"]["low"] <= 0)))
    for key, name in (("without minutes and starts", "Mins"), ("without club and opponent strength", "Club"),
                      ("without season to date", "Season"), ("without prior season", "Prior")):
        m.add(f"abl{name}Mae", num(sens[key]["mae"], 3)); m.add(f"abl{name}Corr", num(sens[key]["corr"], 3))
    m.add("refMae", num(base["mae"], 3)); m.add("refCorr", num(base["corr"], 3))

    # ---------------------------------------------------------- usage
    b, p, pr = usage["base"], usage["with_usage"], usage["paired"]
    table("usage_table.tex", r" & Without usage & With usage & Difference (95\% CI)", [
        f"Mean absolute error$^a$ & {num(b['mae'], 3)} & {num(p['mae'], 3)} & {interval(pr['mae_reduction'], 3)} \\\\",
        f"Correlation & {num(b['corr'], 3)} & {num(p['corr'], 3)} & \\\\",
        f"Captain points per week & {num(b['captain'])} & {num(p['captain'])} & {interval(pr['captain_points'])} \\\\",
        f"Lineup points per week & {num(b['lineup'])} & {num(p['lineup'])} & {interval(pr['lineup_points'])} \\\\",
        f"MAE, players who changed club$^a$ & & & {interval(pr['mae_reduction_movers'], 3)} \\\\",
    ], "lccc")
    m.add("usageMaeGain", interval(pr["mae_reduction"], 3)); m.add("usageMoverGain", interval(pr["mae_reduction_movers"], 3))
    m.add("usageCapGain", interval(pr["captain_points"])); m.add("usageLineGain", interval(pr["lineup_points"]))
    m.add("usageCapHigh", signed(pr["captain_points"]["high"])); m.add("usageLineHigh", signed(pr["lineup_points"]["high"]))
    m.add("usageMovers", f"{100 * usage['coverage']['moved_club_share']:.0f}\\%")

    # --------------------------------------------------------- figure
    entries = [("Captain vs top-100 consensus", cap["versus"]["elite"]), ("Captain vs premium attacker", cap["versus"]["premium"]),
               ("Captain vs recent form", cap["versus"]["form"]), ("Captain vs form $\\times$ fixtures", rc["vs_form_scaled"]["iid"]),
               ("Captain vs ridge regression", rc["vs_regression"]["iid"]),
               (None, None),
               ("Lineup vs managers' own", line["versus"]["manager"]), ("Lineup vs recent form", line["versus"]["form"])]
    lo = min(e["low"] for _, e in entries if e) - 0.3
    hi = max(e["high"] for _, e in entries if e) + 0.3
    import math
    lo_t, hi_t = math.floor(lo), math.ceil(hi)
    out = [r"\begin{tikzpicture}[x=%.3fcm,y=0.62cm]" % (9.0 / (hi_t - lo_t))]
    y = len(entries) + 0.6
    out.append(r"\draw[gray!60] (%d,0.4) -- (%d,0.4);" % (lo_t, hi_t))
    out.append(r"\foreach \x in {%s} { \draw[gray!60] (\x,0.4) -- (\x,0.28) node[below,font=\scriptsize,text=black] {$\x$}; }"
               % ",".join(str(v) for v in range(lo_t, hi_t + 1)))
    out.append(r"\draw[dashed,gray] (0,0.4) -- (0,%.2f);" % (y))
    out.append(r"\node[font=\scriptsize] at (%.2f,-0.5) {Model minus comparator (points per gameweek)};" % ((lo_t + hi_t) / 2))
    for i, (label, e) in enumerate(entries):
        if not label:
            continue
        yy = len(entries) - i
        out.append(r"\node[anchor=east,font=\small] at (%.2f,%.2f) {%s};" % (lo_t - 0.1, yy, label))
        out.append(r"\draw[thick] (%.3f,%.2f) -- (%.3f,%.2f); \fill (%.3f,%.2f) circle (2.3pt);"
                   % (e["low"], yy, e["high"], yy, e["mean"], yy))
    out.append(r"\end{tikzpicture}")
    (HERE / "figure_intervals.tex").write_text("\n".join(out) + "\n")

    # Compact version for the two-column brief.
    brief = [r"\begin{tikzpicture}[x=%.3fcm,y=0.5cm]" % (4.6 / (hi_t - lo_t))]
    brief.append(r"\draw[gray!60] (%d,0.4) -- (%d,0.4);" % (lo_t, hi_t))
    brief.append(r"\foreach \x in {%s} { \draw[gray!60] (\x,0.4) -- (\x,0.28) node[below,font=\tiny,text=black] {$\x$}; }"
                 % ",".join(str(v) for v in range(lo_t, hi_t + 1)))
    brief.append(r"\draw[dashed,gray] (0,0.4) -- (0,%.2f);" % (y))
    for i, (label, e) in enumerate(entries):
        if not label:
            continue
        yy = len(entries) - i
        short = label.replace("Captain vs ", "Captain: ").replace("Lineup vs ", "XI: ")
        brief.append(r"\node[anchor=east,font=\scriptsize] at (%.2f,%.2f) {%s};" % (lo_t - 0.05, yy, short))
        brief.append(r"\draw[thick] (%.3f,%.2f) -- (%.3f,%.2f); \fill (%.3f,%.2f) circle (1.8pt);"
                     % (e["low"], yy, e["high"], yy, e["mean"], yy))
    brief.append(r"\end{tikzpicture}")
    (HERE / "figure_brief.tex").write_text("\n".join(brief) + "\n")

    # ----------------------------------------------------- possession
    med = sorted(v["median"] for v in poss.values())
    m.add("possMedianLow", f"{100 * (med[0] - 1):.0f}"); m.add("possMedianHigh", f"{100 * (med[-1] - 1):.0f}")
    m.add("possPLow", f"{100 * (min(v['p05'] for v in poss.values()) - 1):.0f}")
    m.add("possPHigh", f"{100 * (max(v['p95'] for v in poss.values()) - 1):.0f}")
    m.write()


if __name__ == "__main__":
    main()
